class BatchGD:
  def __init__(self,epochs,learning_rate):
    self.m=None
    self.b=None
    self.epochs=epochs
    self.l_r=learning_rate

  def fit(self,x_train,y_train):



    self.m=np.ones(x_train.shape[1])
    self.b=0
    for i in range(self.epochs):

      y_hat=np.dot(x_train,self.m)+self.b
      m_der=-2*np.dot(x_train.T,(y_train - y_hat)) / x_train.shape[0]
      self.m=self.m-(self.l_r*m_der)
      b_der=-2*np.mean(y_train-y_hat)
      self.b=self.b-(self.l_r * b_der)


    print("m:",self.m,"b:",self.b)

  def predict(self,x_test):
    return np.dot(x_test,self.m)+self.b



