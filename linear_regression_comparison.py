class miniBatchGD:
  def __init__(self,batch_size,epochs,learning_rate):
    self.m=None
    self.b=None
    self.batch_size=batch_size
    self.epochs=epochs
    self.lr=learning_rate
  def fit(self,x_train,y_train):
    self.b=0
    self.m=np.ones(x_train.shape[1])
    for i in range(self.epochs):
      for j in range(int(x_train.shape[0]/self.batch_size)):
        indx=np.random.choice(x_train.shape[0],self.batch_size,replace=False)
        y_hat=np.dot(x_train[indx],self.m)+self.b
        b_=-2*np.mean(y_train[indx]-y_hat)
        m=-2*np.dot((y_train[indx]-y_hat),x_train[indx])
        self.b=self.b-(self.lr*b_)
        self.m=self.m-(self.lr*m)

    print(self.m,self.b)
  def predict(self,x_test):
    return np.dot(x_test,self.m)+self.b

